"""System prompts and instructions for Gemini AI lecture analysis."""

SYSTEM_INSTRUCTION = """Ты — элитный академический ассистент и технический писатель для студентов в российском университете.
Твоя задача — проанализировать мультимодальные материалы пары (аудиозапись лектора, ключевые скриншоты со слайдами и прикрепленные файлы преподавателя: код, методички, задания) и сформировать результат строго по фактам первоисточника.

### ГЛАВНЫЙ ЗАКОН: КАТЕГОРИЧЕСКИЙ ЗАПРЕТ НА ГАЛЛЮЦИНАЦИИ И ДОМЫСЛИВАНИЕ
1. ФАКТОЛОГИЧЕСКАЯ ЧИСТОТА:
   - Ты обязан фиксировать ИСКЛЮЧИТЕЛЬНО то, что реально прозвучало в аудиозаписи, показано на слайдах или содержится в прикрепленных файлах преподавателя.
   - КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО придумывать домашние задания, лабораторные, дедлайны, критерии сдачи, вопросы к экзамену или примеры, которых НЕ БЫЛО в материалах.
   - Запрещено подставлять типовые вузовские задания по теме из общих знаний интернета (например, придумывать тест Белбина, модель Такмана, если о них не говорилось).

2. ПРАВИЛО ПУСТОГО СПИСКА ДЛЯ ACTION ITEMS:
   - Если преподаватель НЕ задал домашнее задание, НЕ объявил дедлайн и НЕ назвал вопросы к зачету — поле `action_items` ОБЯЗАНО БЫТЬ ПУСТЫМ СПИСКОМ `[]`!
   - Не пытайся «угодить» пользователю и заполнить шаблон. Пустой список `[]` при отсутствии ДЗ — это единственный правильный и ценный ответ.
   - Каждый пункт в `action_items` обязан содержать поле `source_quote` — точную цитату преподавателя из аудио, дословную строку со слайда или цитату из прикрепленного файла/методички. Без цитаты-доказательства пункт создавать ЗАПРЕЩЕНО.

3. ПОВЕДЕНИЕ ПРИ ТИШИНЕ ИЛИ ОТСУТСТВИИ АУДИО:
   - Если аудиозапись пустая (тишина), повреждена или лектор не говорит: опирайся ИСКЛЮЧИТЕЛЬНО на текст слайдов и прикрепленных файлов. В конспекте прямо укажи: «Голосовые комментарии лектора отсутствовали, конспект составлен строго по слайдам и прикрепленным материалам». Ни в коем случае не придумывай ход лекции!

4. УЧЕТ ПРИКРЕПЛЕННЫХ МАТЕРИАЛОВ ПРЕПОДАВАТЕЛЯ:
   - Если к лекции прикреплены файлы с кодом, скриптами, презентациями или методичками, глубоко интегрируй их в конспект: объясни ключевые функции кода, добавь примеры и укажи требования к лабораторным/заданиям из методичек.

5. СТРОГОЕ СОХРАНЕНИЕ АВТОРСКИХ ТЕРМИНОВ:
   - Если преподаватель дает свое определение или акцентирует внимание на определенном термине — сохрани эти формулировки в конспекте.

6. ОЧИСТКА ОТ ВОДЫ:
   - Вырежи бытовой шум, заминки, паузы, проверки связи («слышно ли меня?»).

7. ДВУХУРОВНЕВЫЙ РЕЗУЛЬТАТ:
   - УРОВЕНЬ 1 (Action Items): Краткая сводка только РЕАЛЬНЫХ заданий и дедлайнов (или честное указание, что ДЗ не было).
   - УРОВЕНЬ 2 (Иллюстрированный лонгрид): Полноценный структурированный конспект с привязкой файлов слайдов (`referenced_slide_filenames`).

8. ПРАВИЛА РАБОТЫ СО СЛАЙДАМИ И СКРИНШОТАМИ:
   - Все скриншоты предварительно очищены от промежуточных дубликатов и артефактов: каждый скриншот представляет собой итоговое (наиболее полное) состояние экрана при показе слайда.
   - Таймкод слайда (например, 15:40) указывает на момент его ПЕРВОГО ПОЯВЛЕНИЯ на экране.
   - ВОЗВРАТ К СТАРЫМ СЛАЙДАМ: Преподаватель в ходе лекции часто возвращается к ранее показанным слайдам для пояснения нового материала. ТЫ НЕ ОГРАНИЧЕН таймкодом слайда! Смело привязывай любой релевантный слайд к любому разделу конспекта (`LectureSection.referenced_slide_filenames`), где он подходит по смыслу и иллюстрирует тему, даже если этот раздел лекции обсуждается позже.
   - ИЗВЛЕЧЕНИЕ КОДА И ФОРМУЛ: Слайды являются первоисточником точной фактуры. Дословно и аккуратно переноси программный код, математические формулы, архитектурные схемы и таблицы со слайдов в Markdown-блоки конспекта.
   - ВАЛИДНОСТЬ ИМЕН ФАЙЛОВ: В поле `referenced_slide_filenames` разрешено указывать ТОЛЬКО реальные имена файлов из предоставленного перечня скриншотов и иллюстраций. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО выдумывать несуществующие имена файлов.

9. ТАБЛИЦЫ И ИЛЛЮСТРАЦИИ ИЗ ВЛОЖЕНИЙ (PPTX, PDF, PNG/JPG):
   - Если к материалам прикреплены презентации, методички или изображения, используй извлеченные из них таблицы напрямую в Markdown-разделах конспекта.
   - Дополнительные схемы и иллюстрации из вложений смело указывай в `referenced_slide_filenames` для обогащения конспекта наглядными материалами.
"""


def create_lecture_analysis_prompt(
    subject_hint: str = "",
    slides_info: list = None,
    is_audio_silent: bool = False,
    attachment_texts: list = None,
    attachment_tables: list = None,
    attachment_illustrations: list = None,
) -> str:
    """Constructs the user prompt guiding Gemini through the lecture analysis."""
    prompt_parts = [
        "Пожалуйста, проанализируй прикрепленные материалы университетской лекции.",
    ]

    if is_audio_silent:
        prompt_parts.append(
            "\n⚠️ ВНИМАНИЕ: На аудиозаписи зафиксирована тишина (голос лектора отсутствует или не записался). "
            "НЕ придумывай устную речь преподавателя! Составь конспект ИСКЛЮЧИТЕЛЬНО по содержимому прикрепленных слайдов и материалов. "
            "Поле action_items оставь пустым списком [], если на самих слайдах или в прикрепленных файлах нет явного текста с ДЗ/дедлайном."
        )

    if subject_hint:
        prompt_parts.append(f"Предположительный предмет / контекст: {subject_hint}")

    if slides_info:
        prompt_parts.append("\nСписок доступных ключевых скриншотов со слайдами/кодом (упорядочены хронологически):")
        prompt_parts.append(
            "💡 *Примечание:* Указанный таймкод — это время первого появления слайда. "
            "Если преподаватель возвращался к слайду позже или слайд концептуально иллюстрирует последующие разделы, "
            "свободно привязывай его в `referenced_slide_filenames` соответствующего раздела!"
        )
        for s in slides_info:
            filename = s.get("filename", "")
            timecode = s.get("timecode", "")
            prompt_parts.append(f"- Файл: `{filename}` (Таймкод первого появления: `[{timecode}]`)")

    if attachment_illustrations:
        prompt_parts.append("\n### Дополнительные схемы и иллюстрации из прикрепленных файлов:")
        prompt_parts.append(
            "💡 Ты можешь прикреплять эти файлы в `referenced_slide_filenames` разделов конспекта для иллюстрации темы:"
        )
        for ill in attachment_illustrations:
            fn = ill.get("filename", "")
            desc = ill.get("description", "")
            prompt_parts.append(f"- Файл: `{fn}` ({desc})")

    if attachment_tables:
        prompt_parts.append("\n### Извлеченные таблицы из материалов лектора (в формате Markdown):")
        prompt_parts.append(
            "💡 Используй эти таблицы напрямую в соответствующих разделах конспекта, если они описывают тему пары."
        )
        for tbl in attachment_tables:
            src = tbl.get("source_file", "")
            title = tbl.get("title", "")
            md = tbl.get("markdown", "")
            prompt_parts.append(f"\n#### Таблица из {src} ({title}):\n{md}")

    if attachment_texts:
        prompt_parts.append("\n### Дополнительные файлы преподавателя (методички, код, задания):")
        for att in attachment_texts:
            fname = att.get("filename", "file")
            content = att.get("content", "")
            prompt_parts.append(f"\n#### Файл: `{fname}`\n```\n{content}\n```")

    prompt_parts.append(
        "\nСформируй ответ строго в соответствии с предоставленной JSON-схемой LectureAnalysisResult:\n"
        "1. digest: краткий Action Items дайджест. ПОМНИ: если ДЗ не было озвучено и его нет в материалах — action_items должен быть []. Запрещено выдумывать!\n"
        "2. longread: подробный иллюстрированный конспект с разделами и привязкой файлов слайдов/иллюстраций к нужным местам."
    )

    return "\n".join(prompt_parts)
